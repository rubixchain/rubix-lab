#!/usr/bin/env python3
"""
case_book.py - write CASE-BOOK.md: every case, the limit of the software it
finds, and each of its steps - what the lab does and what Rubix must do - from
the case modules' PURPOSE and STEPS, so the book and the code cannot disagree.
A step a case runs must be in its STEPS (master/steps.py refuses one that is
not); this script also refuses a case without PURPOSE or STEPS.

Run after changing a case:
    python3 case_book.py
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import master_cases

HEADER = """# The case book

Generated by `case_book.py` from each case module's `PURPOSE` and `STEPS` -
edit those, not this file.

Every case finds a limit of **the software** - Rubix - and checks that at that
limit Rubix refuses **gently**: with a stated reason, in good time, leaving
nothing behind. A case is a list of steps; each step says what the lab does
and what Rubix must do, and is judged the same way (`steps.py`).

## How a step is judged

Before the step, its preconditions are checked - the lab's set-up, never
blamed on Rubix. Every participant node must be able to receive (its IPFS p2p
listener; nodes that cannot are left out of the whole run). Then the step
reads the participants' wallets and starts watching their machines over SSH
(CPU, disk wait, memory, swap, disk, node restarts, p2p listeners). It runs
the action, waits for every accepted transfer to reach its receiver's node,
gives locks time to clear, and reads the wallets again.

| Outcome | Meaning | The case |
|---|---|---|
| **PASS** | Rubix did what the step expects; every check after it holds | passes |
| **LIMIT** | Rubix could not take all of it and refused the rest **gently**: every refusal named its reason within the budget (60s unless the step says otherwise); nothing left Locked; no value moved that should not have; no counter drifted; no node restarted or went deaf; an ordinary operation went through again afterwards | passes, and records the limit |
| **DAMAGE** | Rubix failed or refused **ungently**: no usable reason (a dropped connection, a raw database error, a panic), too late or never, RBT/FT left Locked, a counter left wrong, a node restarted or went deaf, or no recovery | fails |
| **WRONG** | Rubix accepted what it should have refused, refused what it must accept, or the result is wrong: value created or lost, an accepted transfer that never reached its receiver, two winners of a one-token race | fails |
| **HARDWARE** | the step failed while a machine it ran on was out of CPU (95%), memory (5% left), swap (200 MB filled) or disk (1 GB left) - possibly the machine's limit, not Rubix's | inconclusive (reported as SKIP) |
| **NOT RUN** | a precondition did not hold | not run (SKIP) |

A **capacity** step (a burst, a ladder rung) may meet a limit: a gentle refusal
there is LIMIT. A step whose operations are all valid and must go through has no
such excuse: a refusal there is WRONG, with its reason. Refusals from a
sender's own tokens (a former quorum's unpledged token, a second-hand part
token - both known product bugs) or its clock are counted apart from the limit
a capacity step measures.

What every case keeps out of the way, so a limit found is Rubix's: senders on
other machines than their quorum where it matters, one sender per node before
any node sends twice, wallets of whole tokens the faucet paid, DIDs that were
quorums earlier kept out of the sender seat, every sending node read back to
sign with the step's quorum, quorums funded for every pledge the step can make,
wallets that must hold exactly one token checked to, and nodes that cannot
receive left out.
"""


def main():
    out, problems = [HEADER], []
    for tid in master_cases.ORDER:
        mod = next(m for m in master_cases.CASE_MODULES if tid in m.CASES)
        purpose = (getattr(mod, "PURPOSE", None) or {}).get(tid)
        defs = (getattr(mod, "STEPS", None) or {}).get(tid)
        if not purpose or not defs:
            problems.append("{} ({}) has no {}".format(tid, mod.__name__, "PURPOSE" if not purpose else "STEPS"))
            continue
        ids = [d[0] for d in defs]
        if len(ids) != len(set(ids)):
            problems.append("{} defines a step twice".format(tid))
        out += ["## {}".format(tid), "", purpose, "",
                "| Step | What the lab does | What Rubix must do |", "|---|---|---|"]
        for sid, title, do, expect in defs:
            out.append("| **{}** {} | {} | {} |".format(sid, title, do.replace("|", "/"),
                                                        expect.replace("|", "/")))
        out.append("")
    if problems:
        sys.exit("ERROR: " + "; ".join(problems))
    path = os.path.join(HERE, "CASE-BOOK.md")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print("wrote {} ({} cases)".format(path, len(master_cases.ORDER)))


if __name__ == "__main__":
    main()
